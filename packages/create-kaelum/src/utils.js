const fs = require("node:fs/promises");
const path = require("node:path");

const DEFAULT_ENV = `PORT=3000
NODE_ENV=development
`;

const DEFAULT_GITIGNORE = `node_modules/
dist/
.env
*.log
`;

/**
 * @param {string} target
 * @returns {Promise<boolean>}
 */
async function pathExists(target) {
  try {
    await fs.access(target);
    return true;
  } catch {
    return false;
  }
}

/**
 * Copy a template directory to target and update package.json with projectName.
 * Also generates .env and .gitignore files.
 * @param {string} sourceDir
 * @param {string} targetDir
 * @param {string} projectName (optional) - will override package.json name if present
 * @param {string} kaelumVersion (optional) - range written as the `kaelum` dependency
 */
async function copyTemplate(sourceDir, targetDir, projectName, kaelumVersion) {
  try {
    if (!sourceDir || !targetDir) {
      throw new Error("Source and target directories are required.");
    }

    if (!(await pathExists(sourceDir))) {
      throw new Error(`Template not found: ${sourceDir}`);
    }

    await fs.cp(sourceDir, targetDir, {
      recursive: true,
      // The caller checks the target is missing or empty; never overwrite a file.
      force: false,
    });

    // Try update package.json in the copied template
    const pkgPath = path.join(targetDir, "package.json");
    if (projectName && (await pathExists(pkgPath))) {
      try {
        const pkg = JSON.parse(await fs.readFile(pkgPath, "utf8"));
        // Set sensible defaults for created project
        pkg.name = projectName;
        if (!pkg.version) pkg.version = "0.1.0";
        if (!pkg.description) pkg.description = `${projectName} - generated by create-kaelum`;
        // Never trust the range baked into the template: it goes stale.
        if (kaelumVersion && pkg.dependencies && pkg.dependencies.kaelum) {
          pkg.dependencies.kaelum = kaelumVersion;
        }
        await fs.writeFile(pkgPath, JSON.stringify(pkg, null, 2) + "\n", "utf8");
      } catch (e) {
        // Non-fatal: warn but continue
        console.warn("Warning: failed to update package.json in the template:", e.message);
      }
    }

    const envPath = path.join(targetDir, ".env");
    if (!(await pathExists(envPath))) {
      await fs.writeFile(envPath, DEFAULT_ENV, "utf8");
    }

    const gitignorePath = path.join(targetDir, ".gitignore");
    if (!(await pathExists(gitignorePath))) {
      await fs.writeFile(gitignorePath, DEFAULT_GITIGNORE, "utf8");
    }

    return { ok: true };
  } catch (err) {
    return { ok: false, error: err.message || String(err) };
  }
}

module.exports = { copyTemplate, pathExists };
